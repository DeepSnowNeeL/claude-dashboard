// --- Helpers ---------------------------------------------------------------------------------------------------

const isObject = v => v !== null && typeof v === 'object' && !Array.isArray(v);
const mapValue = (map, v) => (typeof v === 'string' && Object.hasOwn(map, v) ? map[v] : v);

/**
 * Renames the keys of `o` with `map` (shallow); `convert(englishKey, value)` converts each value. A key already in
 * English wins over its French twin (half-migrated object).
 */
function renameKeys(o, map, convert = (k, v) => v) {
  const out = {};
  for (const [k, v] of Object.entries(o)) {
    if (!Object.hasOwn(map, k)) out[k] = convert(k, v);
    else if (!Object.hasOwn(o, map[k]) || map[k] === k) out[map[k]] = convert(map[k], v);
  }
  return out;
}

const escapeRe = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
/**
 * Absolute path into the old data folder → its new location (attachments folder fichiers/ → files/, tracker files).
 * Other strings are returned unchanged. Exported for the driver (attachments named in old transcripts).
 */
export function migrateDataPath(p, dir = dashDir()) {
  if (typeof p !== 'string' || p.length > 2000) return p;
  const base = escapeRe(path.resolve(dir)).replace(/\\\\|\//g, '[\\\\/]');
  const sep = '[\\\\/]';
  const re = new RegExp(`^(${base}${sep})(fichiers(?=${sep})|suivi\\.json$|suivis${sep}depots(?=${sep}))`, 'i');
  return p.replace(re, (m, root, what) => {
    const s = what.toLowerCase();
    if (s.startsWith('fichiers')) return `${root}files`;
    if (s === 'suivi.json') return `${root}tracker.json`;
    return `${root}trackers${what.slice(6, 7)}repos`;
  });
}

// --- Tracker profiles ------------------------------------------------------------------------------------------

/** One block of a profile: { cle, type, titre, consigne } or { cote: [...] }. */
function migrateBlock(b, compositeNames) {
  if (!isObject(b)) return b;
  return renameKeys(b, { cle: 'key', titre: 'title', consigne: 'instruction', cote: 'sideBySide' }, (k, v) => {
    if (k === 'key') return mapValue(KEYS, v);
    if (k === 'type') return compositeNames.has(v) ? v : mapValue(BLOCK_TYPES, v);
    if (k === 'sideBySide') return Array.isArray(v) ? v.map(x => migrateBlock(x, compositeNames)) : v;
    return v;
  });
}

/**
 * A tracker profile file (full profile, `{ profil: "dev" }` reference, or the legacy `{ defaut, projets }` format)
 * → English. Already-English input comes back equal.
 */
export function migrateProfile(p) {
  if (!isObject(p)) return p;
  if ('defaut' in p && !p.blocs && !p.blocks && !('profil' in p) && !('profile' in p)) {
    return { profile: BUILTIN_PROFILES.includes(p.defaut) ? p.defaut : 'simple' };
  }
  const composites = isObject(p.types) ? p.types : {};
  const compositeNames = new Set(Object.keys(composites));
  const out = renameKeys(p, { profil: 'profile', nom: 'name', etapes: 'steps', methode: 'method', blocs: 'blocks' }, (k, v) => {
    if (k === 'profile') return isObject(v) ? migrateProfile(v) : v;
    if (k === 'steps') {
      return Array.isArray(v) ? v.map(s => (isObject(s) ? renameKeys(s, { cle: 'key', libelle: 'label' }, (kk, vv) => (kk === 'key' ? mapValue(STEPS, vv) : vv)) : s)) : v;
    }
    if (k === 'types' && isObject(v)) {
      return Object.fromEntries(Object.entries(v).map(([name, t]) => [name, isObject(t)
        ? renameKeys(t, { rendu: 'layout', champs: 'fields' }, (kk, vv) => {
          if (kk === 'layout') return mapValue(COMPOSITE_LAYOUTS, vv);
          if (kk === 'fields' && Array.isArray(vv)) {
            return vv.map(f => (isObject(f) ? renameKeys(f, { cle: 'key' }, (k3, v3) => (k3 === 'key' ? mapValue(KEYS, v3) : k3 === 'type' ? mapValue(COMPOSITE_FIELD_TYPES, v3) : v3)) : f));
          }
          return vv;
        })
        : t]));
    }
    if (k === 'blocks') return Array.isArray(v) ? v.map(b => migrateBlock(b, compositeNames)) : v;
    return v;
  });
  if (BUILTIN_PROFILES.includes(out.id)) out.name = mapValue(BUILTIN_NAMES, out.name);
  return out;
}

// --- Sessions --------------------------------------------------------------------------------------------------

/** Board content filled by Claude (any depth): keys by KEYS, enum values recognised by the shape of their object. */
function migrateBoardValue(v, dir) {
  if (typeof v === 'string') return migrateDataPath(v, dir);
  if (Array.isArray(v)) return v.map(x => migrateBoardValue(x, dir));
  if (!isObject(v)) return v;
  const o = renameKeys(v, KEYS, (k, x) => migrateBoardValue(x, dir));
  // progress item { label, state }
  if (typeof o.state === 'string' && 'label' in o) o.state = mapValue(PROGRESS_STATES, o.state);
  // decision or architecture element example { type, text | code | left/right: { title, tone } }
  if (isObject(o.example)) {
    const e = o.example;
    if ('type' in e) e.type = mapValue(EXAMPLE_TYPES, e.type);
    for (const side of ['left', 'right']) if (isObject(e[side]) && 'tone' in e[side]) e[side].tone = mapValue(TONES, e[side].tone);
  }
  // architecture { level, layers }
  if (Array.isArray(o.layers) && 'level' in o) o.level = mapValue(ARCHITECTURE_LEVELS, o.level);
  return o;
}

function migrateStats(st) {
  if (!isObject(st)) return st;
  return renameKeys(st, STATS_KEYS, (k, v) => (k === 'achievements' && isObject(v) ? renameKeys(v, ACHIEVEMENT_STATS_KEYS) : v));
}

/** Resolved tracker joined to a session { profil, source, fichier }. */
function migrateResolvedTracker(t, dir) {
  if (!isObject(t)) return t;
  return renameKeys(t, { profil: 'profile', fichier: 'file' }, (k, v) => {
    if (k === 'profile') return migrateProfile(v);
    if (k === 'source') return mapValue(TRACKER_SOURCES, v);
    if (k === 'file' && typeof v === 'string') return migrateDataPath(v, dir).replace(/([\\/])suivis([\\/])(dev|simple)\.json$/, '$1trackers$2$3.json');
    return v;
  });
}

/**
 * One French session object (sessions/<slug>.json, or any subset of its fields, as sent by `dash.mjs push` or
 * rebuilt from an old transcript) → a new English object. Unknown keys are kept as they are; already-English input
 * is returned unchanged (same object).
 */
export function migrateSession(obj, { dir = dashDir() } = {}) {
  if (!isObject(obj)) return obj;
  const out = renameKeys(obj, KEYS, (k, v) => {
    switch (k) {
      case 'stats': return migrateStats(v);
      case 'trackerPreview': return migrateProfile(v);
      case 'tracker': return migrateResolvedTracker(v, dir);
      case 'reportedSchemas': return isObject(v) ? renameKeys(v, KEYS) : v;
      case 'seen': return v;
      case 'status': return mapValue(STATUS, v);
      case 'step': return mapValue(STEPS, v);
      case 'mode': return mapValue(MODES, v);
      case 'title': case 'autoTitle': return mapValue(DEFAULT_TITLES, v);
      case 'slug': case 'sessionId': case 'cwd': case 'description': case 'statusSummary': case 'ticket':
      case 'ticketUrl': case 'project': case 'model': case 'updatedAt': case 'endedAt': case 'archivedAt':
        return v;
      default: return migrateBoardValue(v, dir);
    }
  });
  return JSON.stringify(out) === JSON.stringify(obj) ? obj : out;
}

